/**
 * Shared NOTICE.md generator for workspace packages. Reads license metadata and
 * bundled license text for each direct production dependency from node_modules.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|$)/i;

/** Read an installed dependency's manifest and bundled license text. */
function describe(projectRoot, name) {
  const dir = join(projectRoot, "node_modules", name);
  let manifest = {};
  try {
    manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  } catch {
    return { name, version: "unknown", license: "unknown" };
  }
  const license =
    typeof manifest.license === "string"
      ? manifest.license
      : manifest.license?.type;
  const author =
    typeof manifest.author === "string"
      ? manifest.author
      : manifest.author?.name;
  let text = null;
  try {
    const file = readdirSync(dir).find((f) => LICENSE_FILE.test(f));
    if (file) text = readFileSync(join(dir, file), "utf8").trim();
  } catch {
    // No readable license file; the SPDX id below still documents the terms.
  }
  return {
    name,
    version: manifest.version ?? "unknown",
    license: license ?? "see homepage",
    author,
    homepage: manifest.homepage,
    text,
  };
}

export function generateNotice({ projectRoot, output }) {
  const pkg = JSON.parse(
    readFileSync(join(projectRoot, "package.json"), "utf8"),
  );
  const deps = Object.keys(pkg.dependencies ?? {})
    .sort()
    .map((name) => describe(projectRoot, name));

  const lines = [
    "# Notice",
    "",
    "This application includes the following direct open source dependencies.",
    "It is generated by `scripts/generate-notice.mjs`; do not edit it by hand.",
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
    ...deps.map((d) => `| ${d.name} | ${d.version} | ${d.license} |`),
    "",
    "## License Texts",
    "",
  ];
  for (const d of deps) {
    lines.push(`### ${d.name}@${d.version}`, "");
    lines.push(`- License: ${d.license}`);
    if (d.author) lines.push(`- Author: ${d.author}`);
    if (d.homepage) lines.push(`- Homepage: ${d.homepage}`);
    lines.push("");
    if (d.text) lines.push("```", d.text, "```", "");
  }

  writeFileSync(output, `${lines.join("\n")}\n`);
  process.stdout.write(
    `Wrote NOTICE for ${deps.length} direct dependencies to ${output}\n`,
  );
}
